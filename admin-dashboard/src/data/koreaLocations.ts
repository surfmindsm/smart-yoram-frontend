// 시 목록 가져오기
export const getCities = (): string[] => {
  return Object.keys(koreaLocations);
};

// 특정 시의 구 목록 가져오기
export const getDistricts = (city: string): string[] => {
  return city ? Object.keys(koreaLocations[city] || {}) : [];
};

// 위치 문자열 생성
export const formatLocation = (city?: string, district?: string): string => {
  const parts = [city, district].filter(Boolean);
  return parts.join(' ');
};
